def get_column_index(header, target_col):
    """
    Intelligently parse the target column:
    - Support 1-based index (e.g. '9' represents the 9th column, index 8)
    - Support exact header name match (e.g. 'Data_Hex')
    - Support case-insensitive match
    - Default to the last column if not found
    """
    col_str = str(target_col).strip()
    
    # Try 1-based index conversion
    try:
        col_idx = int(col_str) - 1
        if 0 <= col_idx < len(header):
            return col_idx
    except ValueError:
        pass
    
    # Try exact match
    if col_str in header:
        return header.index(col_str)
        
    # Case-insensitive match
    header_lower = [h.lower() for h in header]
    if col_str.lower() in header_lower:
        return header_lower.index(col_str.lower())
        
    # Default to the last column
    return len(header) - 1


