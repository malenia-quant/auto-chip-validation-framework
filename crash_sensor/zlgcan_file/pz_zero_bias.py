#              CLI Processing
# ==========================================
def process_csv_cli(file_path, target_col="Data_Hex", brief=False):
    if not brief:
        print(f"\n==========================================")
        print(f" Start CLI Processing File: {file_path}")
        print(f" Target Data Column: {target_col}")
        print(f"==========================================")
    if not os.path.exists(file_path):
        print(f"Error: Target file {file_path} does not exist!")
        return False

    processed_values = []
    skipped_count = 0
    malformed_count = 0

    with open(file_path, 'r', encoding='utf-8') as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            print("Error: Target file is empty!")
            return False

        # Locate target column
        col_idx = get_column_index(header, target_col)
        if not brief:
            print(f"Target column located: '{header[col_idx]}' (Col {col_idx + 1})")

        for row in reader:
            if not row:
                continue
            try:
                data_hex_val = row[col_idx].strip()
            except IndexError:
                malformed_count += 1
                continue

            parts = data_hex_val.split()
            if len(parts) < 2:
                malformed_count += 1
                continue

            hex_str = parts[0] + parts[1]

            try:
                val_dec = int(hex_str, 16)
            except ValueError:
                malformed_count += 1
                continue

            # Rule 1: If decimal > 512, subtract 1024
            if val_dec > 512:
                val_dec -= 1024

            # Rule 2: If decimal is 496, filter/skip it
            if val_dec == 496:
                skipped_count += 1
                continue

            processed_values.append(val_dec)

    # Rule 3: Discard the first 1000 initial data points to remove startup/transient noise
    dropped_initial_count = 0
    if len(processed_values) >= 1000:
        processed_values = processed_values[1000:]
        dropped_initial_count = 1000
    else:
        dropped_initial_count = len(processed_values)
        processed_values = []

    if not processed_values:
        print(f"Error: No valid data extracted! (Original valid points: {dropped_initial_count}, insufficient to discard the first 1000 points)")
        return False

    file_dir, full_filename = os.path.split(file_path)
    filename_wo_ext, ext = os.path.splitext(full_filename)

    # 1. Save processed detailed data
    processed_filename = f"{filename_wo_ext}_processed{ext}"
    processed_path = os.path.join(file_dir, processed_filename)

    with open(processed_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['Processed_Value'])
        for val in processed_values:
            writer.writerow([val])

    if not brief:
        print(f"-> [1/2] Converted data saved to: {processed_path}")
        print(f"         (Valid rows: {len(processed_values)}, automatically discarded the first {dropped_initial_count} initial points, filtered 496 values: {skipped_count}, abnormal/insufficient length: {malformed_count})")
    else:
        print(f" [+] Data converted and saved to: {processed_filename}")

    # 2. Fluctuation statistics
    min_val = min(processed_values)
    max_val = max(processed_values)
    span = max_val - min_val
    range_str = f"[{min_val}, {max_val}]"
    mean_val = float(sum(processed_values)) / len(processed_values) if processed_values else 0.0

    # Calculate Zero Bias RMS
    sum_sq = sum(v ** 2 for v in processed_values)
    avg_sq = sum_sq / len(processed_values) if processed_values else 0.0
    rms_val = (avg_sq ** 0.5) * 500

    if not brief:
        print("\n[Zero Bias and Fluctuation Statistics Results]")
        print(f" - Fluctuation Range (Range)    : {range_str}")
        print(f" - Fluctuation Span (Span)      : {span} LSB")
        print(f" - Zero Bias Mean (Mean)        : {mean_val:.3f} LSB")
        print(f" - Zero Bias RMS (RMS)          : {rms_val:.3f} mg")

    # Save zero bias statistics file
    zero_bias_filename = f"{filename_wo_ext}_zero_bias{ext}"
    zero_bias_path = os.path.join(file_dir, zero_bias_filename)

    with open(zero_bias_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['Metric', 'Value'])
        writer.writerow(['Fluctuation Range', range_str])
        writer.writerow(['Fluctuation Span', span])
        writer.writerow(['Zero Bias Mean', f"{mean_val:.3f}"])
        writer.writerow(['Zero Bias RMS', f"{rms_val:.3f}"])

    if not brief:
        print(f"-> [2/2] Zero bias stats saved to: {zero_bias_path}")
        print(f"==========================================\n")
    else:
        print(f" [+] Zero-bias stats calculated and saved to: {zero_bias_filename}")
    return True


def get_latest_csv(folder_path):
    search_pattern = os.path.join(folder_path, "CAN_Record_*.csv")
    csv_files = glob.glob(search_pattern)
    if not csv_files:
        csv_files = glob.glob(os.path.join(folder_path, "*.csv"))
    
    # Exclude already processed results files
    csv_files = [f for f in csv_files if "_processed" not in f and "_zero_bias" not in f]

    if not csv_files:
        return None
    return max(csv_files, key=os.path.getmtime)


