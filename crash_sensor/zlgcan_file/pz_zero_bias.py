            self.log_message("==========================================")
            self.log_message(f" Batch Conversion Started")
            self.log_message(f" Processing Time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
            self.log_message(f" Target Column  : {target_col}")
            self.log_message("==========================================\n")
            
            success_count = 0
            for idx, file_path in enumerate(self.selected_files, start=1):
                self.log_message(f"[{idx}/{len(self.selected_files)}] Processing: {os.path.basename(file_path)}")
                try:
                    res = self.process_single_csv(file_path, target_col)
                    if res:
                        success_count += 1
                except Exception as e:
                    self.log_message(f"-> Serious Exception occurred: {str(e)}\n")
            
            self.log_message("==========================================")
            self.log_message(f" Batch Processing Finished")
            self.log_message(f" Successfully Processed: {success_count}/{len(self.selected_files)}")
            self.log_message("==========================================")
            
            self.root.after(0, self.processing_complete)
            
