"""
pz_zero_bias.py
Used to process CAN data CSV files generated by zcanpro_canfd200u.py.
Features:
1. GUI visualization & batch processing: Support selecting CSV files in batch.
2. Dynamically specify target column: Support specifying column by name ('Data_Hex') or index ('9').
3. High-precision dec conversion: Concat first 2 bytes and convert to decimal.
4. Validation & Filtering:
   - If value > 512, automatically subtract 1024;
   - If value equals 496, automatically filter/skip it.
   - Automatically discard the first 1000 points to remove startup/transient noise.
5. Independent result saving: Save processed details as `_processed.csv` and zero-bias stats as `_zero_bias.csv`.
6. Dual mode execution: Seamlessly switch between GUI and CLI modes.
"""

